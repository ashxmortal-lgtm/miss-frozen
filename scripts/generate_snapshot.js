import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const includedExtensions = new Set([
  '.js', '.jsonc', '.json', '.html', '.css', '.md', '.txt', '.yml', '.yaml'
]);

const excludedPaths = [
  /^\.git\//,
  /^node_modules\//,
  /^package-lock\.json$/,
  /^tgcloud\/lib\/source_snapshot\.js$/,
  /^\.tgcloud\//,
  /^\.env/
];

function collectFiles(dir, base = '') {
  let entries = [];
  const items = fs.readdirSync(dir).sort();
  for (const item of items) {
    if (item === '.git' || item === 'node_modules' || item === '.tgcloud') continue;
    const full = path.join(dir, item);
    const rel = base ? `${base}/${item}` : item;
    const stat = fs.statSync(full);
    if (stat.isDirectory()) {
      entries = entries.concat(collectFiles(full, rel));
    } else {
      if (excludedPaths.some((re) => re.test(rel))) continue;
      const ext = path.extname(item);
      if (includedExtensions.has(ext) || item.startsWith('README')) {
        entries.push(rel);
      }
    }
  }
  return entries;
}

export function generateSnapshotArray(root = repoRoot) {
  const filePaths = collectFiles(root).sort();
  return filePaths.map((rel) => {
    const content = fs.readFileSync(path.join(root, rel), 'utf8');
    return { path: rel, content };
  });
}

function main() {
  const snapshot = generateSnapshotArray(repoRoot);
  const outPath = path.join(repoRoot, 'tgcloud', 'lib', 'source_snapshot.js');

  const fileContent = `/**
 * Bundled source snapshot for owner /backup_all (format: tgcloud-source-snapshot-v1).
 * Auto-generated by scripts/generate_snapshot.js.
 * Contains all restorable repository files: handlers, endpoints, libraries,
 * project source files, configuration, docs, and workflows.
 * Excludes generated dependencies (.git, node_modules) and sensitive secrets.
 */
export const SOURCE_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)};
`;

  fs.writeFileSync(outPath, fileContent, 'utf8');
  console.log(`Generated snapshot with ${snapshot.length} files at ${outPath}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
