import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

// TGCloud rejects a single module over 1,048,576 bytes. Keep each generated
// module comfortably below that so the owner backup stays deployable.
const MAX_MODULE_BYTES = 700 * 1024;

const includedExtensions = new Set([
  '.js', '.jsonc', '.json', '.html', '.css', '.md', '.txt', '.yml', '.yaml'
]);

const excludedPaths = [
  /^\.git\//,
  /^node_modules\//,
  /^package-lock\.json$/,
  /^tgcloud\/lib\/source_snapshot(_\d+)?\.js$/,
  /^\.tgcloud\//,
  /^\.env/
];

function collectFiles(dir, base = '') {
  let entries = [];
  const items = fs.readdirSync(dir).sort();
  for (const item of items) {
    if (item === '.git' || item === 'node_modules' || item === '.tgcloud') continue;
    const full = path.join(dir, item);
    const rel = base ? `${base}/${item}` : item;
    const stat = fs.statSync(full);
    if (stat.isDirectory()) {
      entries = entries.concat(collectFiles(full, rel));
    } else {
      if (excludedPaths.some((re) => re.test(rel))) continue;
      const ext = path.extname(item);
      if (includedExtensions.has(ext) || item.startsWith('README')) {
        entries.push(rel);
      }
    }
  }
  return entries;
}

export function generateSnapshotArray(root = repoRoot) {
  const filePaths = collectFiles(root).sort();
  return filePaths.map((rel) => {
    const content = fs.readFileSync(path.join(root, rel), 'utf8');
    return { path: rel, content };
  });
}

const HEADER = `/**
 * Bundled source snapshot for owner /backup_all (format: tgcloud-source-snapshot-v1).
 * Auto-generated by scripts/generate_snapshot.js — do not edit by hand.
 * Contains all restorable repository files: handlers, endpoints, libraries,
 * project source files, configuration, docs, and workflows.
 * Excludes generated dependencies (.git, node_modules) and sensitive secrets.
 */
`;

function moduleFor(exportName, entries) {
  return `${HEADER}export const ${exportName} = ${JSON.stringify(entries, null, 2)};\n`;
}

/** Split entries into contiguous chunks whose module source stays below the limit. */
function splitEntries(snapshot) {
  const parts = [];
  let current = [];
  let currentBytes = 0;
  const budget = MAX_MODULE_BYTES - 8 * 1024; // header, brackets and margin
  for (const item of snapshot) {
    const itemBytes = Buffer.byteLength(JSON.stringify(item, null, 2), 'utf8') + 4;
    if (itemBytes > budget) {
      throw new Error(`Snapshot entry ${item.path} is ${itemBytes} bytes; it cannot fit in one module`);
    }
    if (current.length && currentBytes + itemBytes > budget) {
      parts.push(current);
      current = [];
      currentBytes = 0;
    }
    current.push(item);
    currentBytes += itemBytes;
  }
  if (current.length) parts.push(current);
  return parts;
}

function removeStaleChunks(outDir) {
  for (const name of fs.readdirSync(outDir)) {
    if (/^source_snapshot_\d+\.js$/.test(name)) fs.unlinkSync(path.join(outDir, name));
  }
}

function main() {
  const snapshot = generateSnapshotArray(repoRoot);
  const outDir = path.join(repoRoot, 'tgcloud', 'lib');
  const outPath = path.join(outDir, 'source_snapshot.js');
  const single = moduleFor('SOURCE_SNAPSHOT', snapshot);

  if (Buffer.byteLength(single, 'utf8') <= MAX_MODULE_BYTES) {
    removeStaleChunks(outDir);
    fs.writeFileSync(outPath, single, 'utf8');
    console.log(`Generated snapshot with ${snapshot.length} files at ${outPath}`);
    return;
  }

  const parts = splitEntries(snapshot);
  const imports = parts
    .map((_, index) => `import { part${index + 1} } from './source_snapshot_${index + 1}.js';`)
    .join('\n');
  const spreads = parts.map((_, index) => `...part${index + 1}`).join(', ');
  const aggregate = `${HEADER}${imports}

export const SOURCE_SNAPSHOT = [${spreads}];
`;

  removeStaleChunks(outDir);
  parts.forEach((entries, index) => {
    const partPath = path.join(outDir, `source_snapshot_${index + 1}.js`);
    fs.writeFileSync(partPath, moduleFor(`part${index + 1}`, entries), 'utf8');
  });
  fs.writeFileSync(outPath, aggregate, 'utf8');
  const sizes = parts.map((entries, index) => {
    const partPath = path.join(outDir, `source_snapshot_${index + 1}.js`);
    return `${path.basename(partPath)}=${fs.statSync(partPath).size}B/${entries.length} files`;
  });
  console.log(
    `Generated snapshot with ${snapshot.length} files in ${parts.length} modules `
    + `(${sizes.join(', ')}), aggregate at ${outPath}`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
